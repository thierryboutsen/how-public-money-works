'use strict';

const fs = require('fs');
const path = require('path');
const siteConfig = require('../site.config');
const { ROOT_DIR } = require('./content-utils');
const { auditOutput } = require('./audit-output');

const EXACT_PUBLIC_FILES = new Set([
  'index.html',
  'insights.html',
  '404.html',
  'sitemap.xml',
  'robots.txt',
  'shared/base.css',
  'shared/main.js'
]);
const PUBLIC_ASSET_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.svg', '.ico', '.woff', '.woff2']);
const TEXT_EXTENSIONS = new Set(['.html', '.css', '.js', '.xml', '.txt', '.svg']);
const PROHIBITED_PUBLIC_PATTERNS = [
  { name: 'AI/tool name', pattern: /\b(?:AI|Artificial Intelligence|ChatGPT|OpenAI|Codex|GPT|LLM|Hermes)\b/i },
  { name: 'agent/prompt/tooling term', pattern: /\b(?:agents?|prompts?|assistant|inference)\b/i },
  { name: 'generation disclosure', pattern: /\b(?:generated by|AI generated|machine generated)\b/i },
  { name: 'editorial automation marker', pattern: /\b(?:automation|editorial engine|workflow|dry[ -]?run|publication gate|auto-publish|fallback|review gate|internal tool)\b/i },
  { name: 'internal publication field', pattern: /\b(?:humanDraftApproval|publicationApproval|publishAllowed|sourceLevel|precisionRisk|canonicalDecision|slugDecision)\b/i },
  { name: 'internal editorial note', pattern: /Editorial review notes|Factual validation checklist|Human draft review/i },
  { name: 'out-of-scope topic', pattern: /\b(?:EB2|NIW|USCIS|immigration)\b/i },
  { name: 'local filesystem path', pattern: /(?:[A-Za-z]:\\|file:\/\/|\/Users\/|\/home\/[^/]+\/)/i },
  { name: 'local or staging host', pattern: /\b(?:localhost|127\.0\.0\.1)\b|https?:\/\/[^\s"'<>]*\.vercel\.app\b/i },
  { name: 'deprecated domain', pattern: /elianafariasima\.com/i }
];
const INTERNAL_ROUTE_PATTERN = /(?:href|src)=["']\/?(?:\.github|docs|scripts|content|review|drafts|editorial|logs|tests|tools|node_modules)(?:\/|["'])/i;
const INTERNAL_COMMENT_PATTERN = /\b(?:TODO|FIXME|DEBUG|Codex|ChatGPT|OpenAI|prompt|automation|workflow|dry[ -]?run|publication gate|review gate|npm run|git branch|commit hash)\b|[A-Za-z]:\\/i;
const JSON_LD_KEYS = new Set([
  '@context', '@type', '@id', 'mainEntityOfPage', 'headline', 'description', 'inLanguage',
  'author', 'publisher', 'name', 'url', 'logo', 'datePublished', 'dateModified', 'image',
  'articleSection', 'keywords'
]);

function listFiles(directory, root = directory) {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...listFiles(fullPath, root));
    else files.push(path.relative(root, fullPath).replace(/\\/g, '/'));
  }
  return files.sort();
}

function isAllowedPublicFile(relativePath) {
  if (EXACT_PUBLIC_FILES.has(relativePath)) return true;
  if (relativePath.endsWith('.html')) return true;
  if (relativePath.startsWith('assets/')) return PUBLIC_ASSET_EXTENSIONS.has(path.extname(relativePath).toLowerCase());
  return false;
}

function inspectJpegMetadata(buffer) {
  const findings = [];
  if (buffer.length < 4 || buffer[0] !== 0xFF || buffer[1] !== 0xD8) return ['invalid-jpeg'];
  let offset = 2;
  while (offset < buffer.length) {
    if (buffer[offset] !== 0xFF) return [...findings, 'malformed-jpeg'];
    while (offset < buffer.length && buffer[offset] === 0xFF) offset += 1;
    const marker = buffer[offset];
    offset += 1;
    if (marker === 0xDA || marker === 0xD9) return findings;
    if (marker === 0x01 || (marker >= 0xD0 && marker <= 0xD7)) continue;
    if (offset + 2 > buffer.length) return [...findings, 'truncated-jpeg'];
    const length = buffer.readUInt16BE(offset);
    const end = offset + length;
    if (length < 2 || end > buffer.length) return [...findings, 'invalid-jpeg-segment'];
    if (marker === 0xE1) findings.push('APP1-EXIF-or-XMP');
    if (marker === 0xED) findings.push('APP13-IPTC');
    if (marker === 0xFE) findings.push('JPEG-comment');
    offset = end;
  }
  return [...findings, 'missing-jpeg-scan'];
}

function inspectPngMetadata(buffer) {
  if (buffer.length < 8 || buffer.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') return ['invalid-png'];
  const findings = [];
  let offset = 8;
  while (offset + 12 <= buffer.length) {
    const length = buffer.readUInt32BE(offset);
    const type = buffer.subarray(offset + 4, offset + 8).toString('ascii');
    if (['eXIf', 'iTXt', 'tEXt', 'zTXt'].includes(type)) findings.push(`PNG-${type}`);
    offset += 12 + length;
    if (type === 'IEND') break;
  }
  return findings;
}

function inspectWebpMetadata(buffer) {
  if (buffer.length < 12 || buffer.subarray(0, 4).toString('ascii') !== 'RIFF' || buffer.subarray(8, 12).toString('ascii') !== 'WEBP') return ['invalid-webp'];
  const text = buffer.toString('latin1');
  return ['EXIF', 'XMP '].filter((chunk) => text.includes(chunk)).map((chunk) => `WEBP-${chunk.trim()}`);
}

function inspectImageMetadata(filePath) {
  const extension = path.extname(filePath).toLowerCase();
  const buffer = fs.readFileSync(filePath);
  if (extension === '.jpg' || extension === '.jpeg') return inspectJpegMetadata(buffer);
  if (extension === '.png') return inspectPngMetadata(buffer);
  if (extension === '.webp') return inspectWebpMetadata(buffer);
  return [];
}

function collectJsonLdKeyErrors(value, location = 'JSON-LD') {
  const errors = [];
  if (Array.isArray(value)) {
    value.forEach((item, index) => errors.push(...collectJsonLdKeyErrors(item, `${location}[${index}]`)));
  } else if (value && typeof value === 'object') {
    for (const [key, nested] of Object.entries(value)) {
      if (!JSON_LD_KEYS.has(key)) errors.push(`${location}: unsupported public key ${key}`);
      errors.push(...collectJsonLdKeyErrors(nested, `${location}.${key}`));
    }
  }
  return errors;
}

function auditText(relativePath, text, assetReferences) {
  const errors = [];
  const scanText = relativePath === 'robots.txt' ? text.replace(/^User-agent:.*$/gmi, '') : text;
  for (const rule of PROHIBITED_PUBLIC_PATTERNS) {
    const match = scanText.match(rule.pattern);
    if (match) errors.push(`${relativePath}: prohibited ${rule.name}: ${match[0]}`);
  }
  if (/sourceMappingURL\s*=/i.test(text)) errors.push(`${relativePath}: public source-map reference found`);
  if (INTERNAL_ROUTE_PATTERN.test(text)) errors.push(`${relativePath}: contains a link to an internal repository route`);
  if (/console\.(?:log|debug|warn|error)\s*\(/.test(text) && relativePath.endsWith('.js')) errors.push(`${relativePath}: contains browser console output`);
  if (relativePath.endsWith('.html')) {
    if (/<meta\b[^>]*\bname=["']generator["']/i.test(text)) errors.push(`${relativePath}: contains meta generator`);
    for (const comment of text.match(/<!--[\s\S]*?-->/g) || []) {
      if (INTERNAL_COMMENT_PATTERN.test(comment)) errors.push(`${relativePath}: contains an internal HTML comment`);
    }
    for (const match of text.matchAll(/<script\s+type=["']application\/ld\+json["']>([\s\S]*?)<\/script>/gi)) {
      try {
        const jsonLd = JSON.parse(match[1].trim());
        errors.push(...collectJsonLdKeyErrors(jsonLd).map((error) => `${relativePath}: ${error}`));
      } catch (error) {
        errors.push(`${relativePath}: invalid JSON-LD during exposure audit: ${error.message}`);
      }
    }
  }
  for (const match of text.matchAll(/\/?assets\/[A-Za-z0-9][A-Za-z0-9._/-]*/g)) {
    assetReferences.add(match[0].replace(/^\//, ''));
  }
  return errors;
}

function auditPublicExposure(outputDirectory, options = {}) {
  const resolvedOutput = path.resolve(outputDirectory);
  if (!fs.existsSync(resolvedOutput)) return { errors: [`output directory not found: ${resolvedOutput}`], warnings: [], files: [], assets: [] };
  const contentAudit = auditOutput(resolvedOutput, { preview: options.preview === true });
  const errors = contentAudit.errors.map((error) => `content audit: ${error}`);
  const warnings = [...(contentAudit.warnings || [])];
  const files = listFiles(resolvedOutput);
  const assetReferences = new Set();

  for (const relativePath of files) {
    if (!isAllowedPublicFile(relativePath)) errors.push(`${relativePath}: file is outside the public output allowlist`);
    if (relativePath.endsWith('.map')) errors.push(`${relativePath}: source maps are prohibited`);
    const fullPath = path.join(resolvedOutput, ...relativePath.split('/'));
    if (TEXT_EXTENSIONS.has(path.extname(relativePath).toLowerCase())) {
      errors.push(...auditText(relativePath, fs.readFileSync(fullPath, 'utf8'), assetReferences));
    }
    if (relativePath.startsWith('assets/') && PUBLIC_ASSET_EXTENSIONS.has(path.extname(relativePath).toLowerCase())) {
      for (const finding of inspectImageMetadata(fullPath)) errors.push(`${relativePath}: public image contains ${finding}`);
    }
  }

  const publicAssets = files.filter((file) => file.startsWith('assets/'));
  for (const asset of publicAssets) {
    if (!assetReferences.has(asset)) errors.push(`${asset}: public asset is not referenced by generated public output`);
  }
  for (const asset of assetReferences) {
    if (!files.includes(asset)) errors.push(`${asset}: referenced public asset is missing`);
  }

  return { errors: [...new Set(errors)], warnings, files, assets: publicAssets, siteOrigin: siteConfig.siteOrigin };
}

function main() {
  const requestedDirectory = process.argv[2] && !process.argv[2].startsWith('--') ? process.argv[2] : 'dist';
  const preview = process.argv.includes('--preview') || requestedDirectory === '.preview';
  const result = auditPublicExposure(path.resolve(ROOT_DIR, requestedDirectory), { preview });
  for (const warning of result.warnings) console.warn(`Warning: ${warning}`);
  if (result.errors.length) {
    console.error(`Public exposure audit failed with ${result.errors.length} error(s):`);
    for (const error of result.errors) console.error(`- ${error}`);
    process.exitCode = 1;
    return;
  }
  console.log(`Public exposure audit passed for ${result.files.length} file(s) and ${result.assets.length} referenced public asset(s) in ${requestedDirectory}.`);
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(error.stack || error.message);
    process.exitCode = 1;
  }
}

module.exports = {
  auditPublicExposure,
  auditText,
  inspectImageMetadata,
  inspectJpegMetadata,
  isAllowedPublicFile,
  listFiles
};
